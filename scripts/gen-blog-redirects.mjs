// Generate the nginx map of legacy root-level blog URLs -> /blog/* equivalents.
//
//   node scripts/gen-blog-redirects.mjs > deploy/blog_redirects.map
//
// Every published post, category and tag currently lives at the site root; under
// basePath they move under /blog. Both bare and trailing-slash forms are emitted,
// because either may be the indexed variant.
//
// Deliberately NOT redirected: /sitemap.xml, /robots.txt and /rss.xml. Those belong
// to the existing website at the root, and hijacking them would break its own SEO.
import 'dotenv/config';
import pg from 'pg';

const BASE = '/blog';

const rows = [];
const push = (from, to) => {
  rows.push([from, to]);
  rows.push([`${from}/`, to]);
};

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();
try {
  const posts = await client.query(
    `select slug from "Post" where status = 'PUBLISHED' and "publishedAt" <= now() order by slug`,
  );
  for (const { slug } of posts.rows) push(`/${slug}`, `${BASE}/${slug}`);

  const cats = await client.query(`select slug from "Category" order by slug`);
  for (const { slug } of cats.rows) push(`/category/${slug}`, `${BASE}/category/${slug}`);

  const tags = await client.query(`select slug from "Tag" order by slug`);
  for (const { slug } of tags.rows) push(`/tag/${slug}`, `${BASE}/tag/${slug}`);

  push('/search', `${BASE}/search`);
} finally {
  await client.end();
}

const width = Math.max(...rows.map(([f]) => f.length)) + 2;
const out = [
  '# Generated by scripts/gen-blog-redirects.mjs — do not hand-edit.',
  '# Legacy root-level blog URLs -> their /blog equivalents.',
  `# ${rows.length} entries.`,
  '',
  ...rows.map(([from, to]) => `${from.padEnd(width)}${to};`),
  '',
].join('\n');

process.stdout.write(out);
process.stderr.write(`generated ${rows.length} redirect entries\n`);
